#!/usr/bin/env python3
"""Disassemble the loader pieces on disk 1 into projects/gods/native/src/amiga/loader.asm and prove they reassemble exactly.

    uv run python projects/gods/scripts/gen_loader_asm.py

Each piece is a byte range of disk 1 that runs at a known address.  Instructions come from the executed-code
coverage (only variants equal to the disk bytes), everything else is `dc.w` data, so the result is byte-identical by
construction and is checked by assembling with vasm (-Fbin -no-opt) and comparing with the disk.
"""
from __future__ import annotations

import glob
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import intro_analysis as G  # noqa: E402

SRC = G.ROOT / "native" / "src"
BUILD = G.ROOT / "native" / "build"
DISK1 = Path(glob.glob(str(G.ROOT / "local/media-archive/disk1/*.adf"))[0])

# (name, first disk byte, length, address it runs at, comment)
PIECES = [
    ("bootblock", 0, 1024, 0x1558, "boot block: loaded by Kickstart at $1558, entered at $1564"),
    ("entry", 0x600, 0x38, 0x59e8, "disk $600: first routine, runs at $59E8 and is copied to $7FF00"),
    ("stage", 0x638, 0x90c, 0xb4, "disk $638: trackloader stage, runs at $B4-$9C0"),
    ("decruncher", 0x52a00, 0xba, 0x76dfc, "disk $52A00: decruncher, copied to $76DFC and called with jsr (a0)"),
]


# The C game is loaded to chip RAM (the original loader uses only chip RAM), where its code is fetched over the same bus as the original's.  The stage is patched in place in three
# places: the jump that ends it goes to the entry in slow RAM instead of $84; a call replaces the `lea` before the
# first disk read, and a small hook in an unused part of the stage reads the blob from free sectors of the disk and
# copies it to slow RAM.
SLOW_BASE = 0x80000    # chip RAM above the original's 512 KB (the machine is given 1 MB chip: puae_chipmem_size=2)
STAGING = 0x10000               # chip RAM that is still unused when the hook runs
HOOK = 0x334                    # 126 unused bytes of the stage
HOOK_SIZE = 126


EXTRA_SECTOR = 1400   # the C is stored in sectors after the last file of disk 1 (tocache.bin ends at 1332; the directory names nothing after it): an emulated drive takes at most 83 cylinders, so there are no extra cylinders


def hook_asm(sectors: int, intro_longs: int, menu_longs: int, menu_base: int) -> list[str]:
    """Read the C (the intro, then the menu) from the extra cylinders into STAGING and copy the two parts to where they run."""
    out = ["        ; ---- hook: read the C from the extra cylinders and copy it to where it runs (replaces unused bytes)",
           f"        org ${HOOK:x}", "        movem.l d0-d7/a0-a6,-(a7)", "        lea.l $9c0(pc),a1", f"        movea.l #${STAGING:x},a0",
           "        moveq #0,d0", f"        move.w #{EXTRA_SECTOR},d1", f"        moveq #{sectors},d2" if sectors < 128 else f"        move.w #{sectors},d2",
           "        moveq #0,d3", "        bsr.w $15a",
           f"        movea.l #${STAGING:x},a0", f"        movea.l #${SLOW_BASE:x},a1", f"        move.w #{intro_longs - 1},d0",
           ".copy:  move.l (a0)+,(a1)+", "        dbra d0,.copy",
           f"        movea.l #${menu_base:x},a1", f"        move.w #{menu_longs - 1},d0",
           ".copy2: move.l (a0)+,(a1)+", "        dbra d0,.copy2",
           "        movem.l (a7)+,d0-d7/a0-a6", "        lea.l $9c0(pc),a1", "        rts", f"        org ${HOOK + HOOK_SIZE:x}"]
    return out


def vasm(src: Path, out: Path) -> subprocess.CompletedProcess:
    cmd = f"vasmm68k_mot -Fbin -no-opt -quiet -o {out} {src}"
    return subprocess.run(["nix", "develop", str(SRC.parent), "--command", "sh", "-c", cmd], capture_output=True, text=True)


def gas_to_vasm(mn: str, ops: str) -> str:
    """capstone text -> vasm Motorola syntax (capstone prints bit operations on a data register with .b)."""
    base, _, _ = mn.partition(".")
    if base in ("btst", "bset", "bclr", "bchg") and ops.rsplit(",", 1)[-1].strip().startswith("d"):
        mn = base + ".l"
    return f"{mn} {ops.replace(', ', ',')}".strip()


def main(patched: bool = False, adf_out: Path | None = None, blob: bytes = b"", menu_blob: bytes = b"", menu_base: int = 0, menu_entry: int = 0) -> int:
    from capstone import CS_ARCH_M68K, CS_MODE_BIG_ENDIAN, CS_MODE_M68K_000, Cs

    md = Cs(CS_ARCH_M68K, CS_MODE_M68K_000 | CS_MODE_BIG_ENDIAN)
    cov = G.read_coverage()
    disk = DISK1.read_bytes()
    BUILD.mkdir(exist_ok=True)
    ok = True
    text = ["; Gods loader, disassembled from the executed code of the original PAL disk 1 and checked byte for byte.",
            "; Generated by projects/gods/scripts/gen_loader_asm.py.  Instructions are the ones the recording executed;",
            "; everything else is data (dc.w).  Assemble: vasmm68k_mot -Fbin -no-opt.", ""]
    patches: dict[tuple[str, int], tuple[list[str], int]] = {}
    allowed: dict[str, list[tuple[int, int]]] = {}
    if patched:
        patches[("stage", 0xb8)] = ([f"        move.l #${SLOW_BASE:x},$2(a0)   ; PATCH: the stage's last jump goes to the C entry, not $84"], 8)
        patches[("stage", 0xf6)] = ([f"        bsr.w ${HOOK:x}   ; PATCH: the hook reads the C blob first"], 4)
        intro_bytes = -(-len(blob) // 4) * 4
        sectors = -(-(intro_bytes + len(menu_blob)) // 512)
        patches[("stage", HOOK)] = (hook_asm(sectors, intro_bytes // 4, -(-len(menu_blob) // 4), menu_base), HOOK_SIZE)
        # the read routine refuses sectors beyond the 1760 of a disk: the limit is raised for the extra cylinders (the C is read from there)
        limit = 1760   # the read routine's own limit: the C is inside the disk
        patches[("stage", 0x19a)] = ([f"        cmp.w #${limit:x},d3   ; PATCH: the limit of the read is {limit} sectors (the cylinders of the C), not 1760"], 4)
        allowed["stage"] = [(0x19a - 0xb4, 0x19a - 0xb4 + 4), (0xb8 - 0xb4, 0xb8 - 0xb4 + 8), (0xf6 - 0xb4, 0xf6 - 0xb4 + 4), (HOOK - 0xb4, HOOK - 0xb4 + HOOK_SIZE)]
    for name, start, length, base, comment in PIECES:
        data = disk[start : start + length]
        text += [f"; ---- {name}: {comment}", f"        org ${base:x}", ""]
        off = 0
        while off < length:
            pc = base + off
            if (name, pc) in patches:
                lines_, nbytes = patches[(name, pc)]
                text.extend(lines_)
                off += nbytes
                continue
            ins = None
            for v in cov.get(pc, []):
                n = min(len(v), length - off)
                if data[off : off + n] == v[:n]:
                    ins = next(md.disasm(data[off : off + 10], pc), None)
                    if ins and data[off : off + ins.size] == v[: ins.size]:
                        break
                    ins = None
            if ins:
                text.append(f"L{pc:05x}:  {gas_to_vasm(ins.mnemonic, ins.op_str):<34}; ${pc:05x}")
                off += ins.size
            else:
                end = off
                while end < length and end - off < 16 and not any(
                        data[end : end + len(v)] == v[: len(v)] for v in cov.get(base + end, [])):
                    end += 2
                end = max(end, off + 2)
                words = [f"${int.from_bytes(data[i : i + 2], 'big'):04x}" for i in range(off, min(end, length), 2)]
                text.append(f"        dc.w {','.join(words)}")
                off = end
        text.append("")
    src = SRC / "amiga" / "loader.asm"
    src.write_text("\n".join(text) + "\n")
    # vasm's flat binary output pads between org addresses, so each piece is assembled on its own
    pieces = re.split(r"(?m)^(?=; ---- )", src.read_text())[1:]
    ok = True
    total = 0
    new_pieces: dict[str, tuple[int, bytes]] = {}
    for (name, start, length, base, _), body in zip(PIECES, pieces):
        psrc = BUILD / f"{name}.asm"
        psrc.write_text(body)
        out = BUILD / f"{name}.bin"
        out.unlink(missing_ok=True)
        r = vasm(psrc, out)
        if r.returncode or not out.exists():
            print(f"{name}: vasm failed:\n", r.stdout[-1500:], r.stderr[-1500:])
            return 1
        built, want = out.read_bytes(), disk[start : start + length]
        if patched and len(built) == len(want):
            ok_ranges = allowed.get(name, [])
            diff = [i for i in range(len(built)) if built[i] != want[i] and not any(a <= i < b for a, b in ok_ranges)]
            if not diff:
                print(f"{name}: {len(built)} bytes, identical to disk 1 except the patched ranges {[(hex(a), hex(b)) for a, b in ok_ranges]}")
                total += len(built)
                new_pieces[name] = (start, built)
                continue
        if built == want:
            new_pieces[name] = (start, built)
            print(f"{name}: {len(built)} bytes identical to disk 1 (${start:x}, runs at ${base:x})")
            total += len(built)
        else:
            i = next((k for k in range(min(len(built), len(want))) if built[k] != want[k]), min(len(built), len(want)))
            print(f"{name}: MISMATCH built {len(built)} want {len(want)} bytes; first difference at +{i:#x}: "
                  f"built {built[i:i+8].hex()} want {want[i:i+8].hex()}")
            ok = False
    print(f"loader.asm: {len(PIECES)} pieces, {total} bytes verified" if ok else "loader.asm: NOT identical")
    if ok and adf_out is not None:
        image = bytearray(disk)
        for start, built in new_pieces.values():
            image[start : start + len(built)] = built
        packed = blob + bytes(intro_bytes - len(blob)) + menu_blob
        cylinders = max(0, -(-(EXTRA_SECTOR + sectors) // 22) - 80)
        assert cylinders == 0, "the C does not fit in bm.1's sectors"
        image[EXTRA_SECTOR * 512 : EXTRA_SECTOR * 512 + len(packed)] = packed
        if menu_entry:   # the menu program's image is raw on the disk: its first code jumps to the start-up ($39E50), which becomes the C entry
            start = bytes.fromhex("2e7c000780002f3c0000240c4ef9")
            at = image.find(start + (0x39E50).to_bytes(4, "big"))
            assert at >= 0 and image.find(start, at + 1) < 0, "the menu image's entry code is not on the disk (once)"
            image[at + len(start) : at + len(start) + 4] = menu_entry.to_bytes(4, "big")
        adf_out.write_bytes(bytes(image))
        print(f"{adf_out}: disk 1 with {cylinders} extra cylinders: the intro ({len(blob)} bytes) and the menu ({len(menu_blob)} bytes) in sectors {EXTRA_SECTOR}..{EXTRA_SECTOR + sectors - 1}")
    return 0 if ok else 1


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--adf", type=Path, help="write disk 1 with the patched stage and the blob")
    ap.add_argument("--blob", type=Path, help="the C blob (relocated for slow RAM)")
    args = ap.parse_args()
    raise SystemExit(main(patched=args.adf is not None, adf_out=args.adf,
                          blob=args.blob.read_bytes() if args.blob else b""))
