"""Write native/src/menu_symbols.h, native/src/data.c and native/src/menu.ld from native/src/menu.symbols (the menu's data at the
addresses the original program keeps it at).

menu.symbols has two kinds of lines:
  NAME ADDRESS DECLARATION   a variable: the declaration has %s for the name; the linker script gives the name its address
  table NAME ADDRESS TYPE COUNT   read-only data: COUNT values of TYPE (char, uint8_t, uint16_t, uint32_t, big endian; a char table is a text) copied from
                             the original program's memory (native/build/menu-ram.bin) into data.c as C initializers; the linker
                             script places the array at the address, so the C reads the same bytes at the same place
After the two fields of a variable's comment or a table's, two or more spaces start a comment.

    uv run python projects/gods/scripts/gen_menu_symbols.py
"""
import re
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
SRC = PROJECT / "native" / "src"
RAM = PROJECT / "native" / "build" / "menu-ram.bin"
WIDTH = {"char": 1, "uint8_t": 1, "uint16_t": 2, "uint32_t": 4}
# the structs of menu_types.h that a table can have: the fields in order, (width in bytes, signed) (big endian in the original's memory)
STRUCT_FIELDS = {
    "CreatureEntry": [(2, 1), (2, 1), (1, 1), (1, 0), (2, 1), (1, 0), (1, 0), (2, 0), (1, 0), (1, 0), (1, 0), (1, 0)],
    "CreatureTemplate": [(2, 0), (2, 0), (4, 0), (2, 0), (2, 0), (4, 0)],
    "Unit": [(2, 0), (1, 0), (1, 0), (2, 0), (1, 0), (1, 0), (1, 0), (1, 0), (4, 0), (2, 1), (2, 1), (4, 0), (1, 0), (1, 0)],
    "LeverFlag": [(2, 0), (2, 0), (2, 0)],
    "WalkMode": [(4, 0), (4, 0)],
    "SoundRecord": [(1, 0)] * 6,
    "SoundInstrument": [(2, 1), (2, 0), (2, 0), (4, 0), (4, 0)],
    "LevelEnd": [(2, 0), (4, 0)] + [(1, 0)] * 20 + [(2, 0), (4, 0), (2, 0)],
    "LevelEnds": ([(2, 0), (4, 0)] + [(1, 0)] * 20 + [(2, 0), (4, 0), (2, 0)]) * 4 + [(2, 0)] + ([(2, 0), (4, 0)] + [(1, 0)] * 20 + [(2, 0), (4, 0), (2, 0)]) * 3 + [(2, 0), (4, 0)] + [(1, 0)] * 20 + [(2, 0), (4, 0)] + ([(2, 0), (4, 0)] + [(1, 0)] * 20 + [(2, 0), (4, 0), (2, 0)]) + [(2, 0)] + ([(2, 0), (4, 0)] + [(1, 0)] * 20 + [(2, 0), (4, 0), (2, 0)]) * 8,
    "PathDescription": [(2, 1), (2, 1), (1, 1), (1, 1)] + [(2, 1)] * 8 + [(1, 1)] * 4 + [(1, 0), (1, 1)],
}


def parse() -> tuple[list, list]:
    variables, tables = [], []
    for line in (SRC / "menu.symbols").read_text().split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        t = re.match(r"table\s+(\w+)\s+(0x[0-9a-fA-F]+)\s+(uint\d+_t|char|struct \w+)\s+(\d+)(?:\s{2,}(.*))?$", line)
        if t:
            tables.append((t.group(1), int(t.group(2), 16), t.group(3), int(t.group(4)), (t.group(5) or "").strip()))
            continue
        m = re.match(r"(\w+)\s+(0x[0-9a-fA-F]+)\s+(.*?%s.*?)(?:\s{2,}(.*))?$", line)
        if not m:
            raise SystemExit(f"menu.symbols: cannot read {line!r}")
        variables.append((m.group(1), int(m.group(2), 16), m.group(3).strip(), (m.group(4) or "").strip()))
    return variables, tables


def main(code_base: int = 0xC0000) -> None:
    variables, tables = parse()
    h = ["/* Generated by scripts/gen_menu_symbols.py from menu.symbols; do not edit. */", "#ifndef MENU_SYMBOLS_H", "#define MENU_SYMBOLS_H", "",
         "#include <stdint.h>", "", '#include "menu_types.h"', ""]
    for name, addr, decl, comment in variables:
        h.append(f"extern {decl.replace('%s', name)};   /* ${addr:05X}" + (f"  {comment}" if comment else "") + " */")
    for name, addr, ctype, count, comment in tables:
        h.append(f"extern const {ctype} {name}[{count}];   /* ${addr:05X}" + (f"  {comment}" if comment else "") + " */")
    h += ["", "#endif", ""]
    (SRC / "menu_symbols.h").write_text("\n".join(h))
    ld = ["/* Generated by scripts/gen_menu_symbols.py from menu.symbols; do not edit.  The menu's code is one hunk; its variables",
          " * are where the original program keeps them (the loader puts them there), so their names are absolute, and the tables",
          " * are placed at their addresses in a hunk of their own, which is never loaded (the bytes are already there).  The code",
          f" * is linked at the address it will run at (${code_base:x}), so it needs no relocation. */",
          "SECTIONS {"]
    if tables:
        ld += ["    .data : SUBALIGN(1) {"]
        ld += [f"        . = 0x{addr:x}; *(.rodata.{name}) *(.data.{name})" for name, addr, _, _, _ in sorted(tables, key=lambda t: t[1])]
        ld += ["    }"]
    ld += [f"    .text 0x{code_base:x} : {{ *(.text .text.*) *(.rodata .rodata.*) }}", "}", ""]
    ld += [f"_{name} = 0x{addr:x};" for name, addr, _, _ in variables]
    (SRC / "menu.ld").write_text("\n".join(ld) + "\n")
    # the tables' data
    if tables:
        ram = RAM.read_bytes()
        c = ["/* Generated by scripts/gen_menu_symbols.py from menu.symbols and the original program's memory; do not edit.",
             " * The tables of the menu program, as C initializers.  menu.ld places each at the address the original keeps it at. */",
             '#include "menu_symbols.h"', ""]
        for name, addr, ctype, count, comment in tables:
            if ctype.startswith("struct "):
                fields = STRUCT_FIELDS[ctype.split()[1]]
                size = sum(f[0] for f in fields)
                c.append(f"/* ${addr:05X}" + (f"  {comment}" if comment else "") + " */")
                c.append(f"const {ctype} {name}[{count}] __attribute__((aligned(1))) = {{")
                for i in range(count):
                    at, items = addr + i * size, []
                    for width, signed in fields:
                        items.append(str(int.from_bytes(ram[at:at + width], "big", signed=bool(signed))))
                        at += width
                    c.append("    { " + ", ".join(items) + " },")
                c += ["};", ""]
                continue
            w = WIDTH[ctype]
            if ctype == "char":   # a text: a string literal (the bytes are as the original has them; the zeros at the end are the array's own)
                raw = ram[addr:addr + count].rstrip(b"\0")
                lit = "".join(chr(b) if 32 <= b < 127 and chr(b) not in '"\\' else f"\\{b:03o}" for b in raw)
                c.append(f"/* ${addr:05X}" + (f"  {comment}" if comment else "") + " */")
                c.append(f'const char {name}[{count}] __attribute__((aligned(1))) = "{lit}";')
                c.append("")
                continue
            vals = [int.from_bytes(ram[addr + i * w:addr + (i + 1) * w], "big") for i in range(count)]
            per = 16 // w if w > 1 else 16
            c.append(f"/* ${addr:05X}" + (f"  {comment}" if comment else "") + " */")
            c.append(f"const {ctype} {name}[{count}]" + (" __attribute__((aligned(1)))" if ctype == "uint8_t" else "") + " = {")
            for i in range(0, count, per):
                c.append("    " + ", ".join(f"0x{v:0{2 * w}x}" for v in vals[i:i + per]) + ",")
            c += ["};", ""]
        (SRC / "data.c").write_text("\n".join(c))
    print(f"wrote menu_symbols.h, menu.ld and data.c ({len(variables)} variables, {len(tables)} tables)")


if __name__ == "__main__":
    main()
