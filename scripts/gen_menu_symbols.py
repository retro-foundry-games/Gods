"""Write native/menu_symbols.h and native/menu.ld from native/menu.symbols (the menu's data at the addresses the original
program keeps it at; the C declares the data and the linker script gives the names their addresses).

    uv run python projects/gods/scripts/gen_menu_symbols.py
"""
import re
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1] / "native"


def symbols() -> list[tuple[str, int, str, str]]:
    out = []
    for line in (NATIVE / "menu.symbols").read_text().split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        m = re.match(r"(\w+)\s+(0x[0-9a-fA-F]+)\s+(.*?%s.*?)(?:\s{2,}(.*))?$", line)
        if not m:
            raise SystemExit(f"menu.symbols: cannot read {line!r}")
        out.append((m.group(1), int(m.group(2), 16), m.group(3).strip(), (m.group(4) or "").strip()))
    return out


def main() -> None:
    syms = symbols()
    h = ["/* Generated by scripts/gen_menu_symbols.py from menu.symbols; do not edit. */", "#ifndef MENU_SYMBOLS_H", "#define MENU_SYMBOLS_H", "",
         "#include <stdint.h>", "", '#include "menu_types.h"', ""]
    for name, addr, decl, comment in syms:
        h.append(f"extern {decl.replace('%s', name)};   /* ${addr:05X}" + (f"  {comment}" if comment else "") + " */")
    h += ["", "#endif", ""]
    (NATIVE / "menu_symbols.h").write_text("\n".join(h))
    ld = ["/* Generated by scripts/gen_menu_symbols.py from menu.symbols; do not edit.  The menu's code is linked as one hunk;",
          " * its data is where the original program keeps it (the loader puts it there), so the names are absolute. */",
          "SECTIONS { .text : { *(.text .text.*) *(.rodata .rodata.*) } }", ""]
    ld += [f"_{name} = 0x{addr:x};" for name, addr, _, _ in syms]
    (NATIVE / "menu.ld").write_text("\n".join(ld) + "\n")
    print(f"wrote menu_symbols.h and menu.ld ({len(syms)} symbols)")


if __name__ == "__main__":
    main()
