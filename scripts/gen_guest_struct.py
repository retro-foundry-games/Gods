#!/usr/bin/env python3
"""Write native/src/guest_struct.h: every variable of menu.symbols as a member of one struct (struct Guest), at the offset of its original address.

    uv run python projects/gods/scripts/gen_guest_struct.py       (needs a host gcc: the sizes of the types are asked of it)

The struct is the program's memory below its heap: a variable that the original keeps at $0248 is the member at offset $248 (padding between), variables that overlap
(a word and the byte in it, a record and the words of it) are the members of an anonymous union at the first of them.  On the Amiga the struct is the memory at address 0
(the linker script says `guest = 0`), everywhere else it is an object of its own; either way it is the one block that a save state is: a RAM image of the original's
memory is its bytes (made native), see native/src/sdl/guest.c.
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
SRC = PROJECT / "native" / "src"
SIZES = {"char": 1, "uint8_t": 1, "uint16_t": 2, "uint32_t": 4, "int8_t": 1, "int16_t": 2, "int32_t": 4}
# how far an unsized array goes where the code uses a block that holds other variables of the original's (the level's tables are read to data_1aa66, 7000 bytes and a text table after them)
EXTENT = {"data_1aa66": 0x1c700, "shadow_table": 0xe50, "copper_list_a": 0x4e3a, "copper_list_b": 0x4e3a}
HEAP = 0x80400   # where the program's heap begins (host.c: heap_base)
GUEST_END = 0x200000


def parse():
    variables = []
    for line in (SRC / "menu.symbols").read_text().split("\n"):
        if not line.strip() or line.startswith("#") or line.split()[0] == "table":
            continue
        m = re.match(r"(\w+)\s+(0x[0-9a-fA-F]+)\s+(.*?%s.*?)(?:\s{2,}(.*))?$", line)
        decl = m.group(3).strip()
        if re.match(r".*?\s*%s\(void\)", decl) and "(*" not in decl:
            continue   # a routine of the original's code (a stub)
        variables.append((m.group(1), int(m.group(2), 16), decl))
    return variables


def tables():
    out = []
    for line in (SRC / "menu.symbols").read_text().split("\n"):
        t = re.match(r"table\s+(\w+)\s+(0x[0-9a-fA-F]+)\s+(uint\d+_t|char|struct \w+)\s+(\d+)", line)
        if t:
            out.append((t.group(1), int(t.group(2), 16)))
    return out


def sizes(variables):
    """sizeof of each variable's declaration, by the host compiler (packed to 2 as the 68000's structs are)"""
    lines = ['#include <stdio.h>', '#include <stddef.h>', '#include "menu_types.h"', "int main(void) {"]
    for name, addr, decl in variables:
        if re.search(r"%s\[\]", decl):
            lines.append(f'    printf("{name} 0\\n");')
            continue
        lines.append(f'    printf("{name} %zu\\n", sizeof({decl.replace("%s", "")}));')
    lines.append("    return 0; }")
    with tempfile.TemporaryDirectory() as tmp:
        c = Path(tmp) / "probe.c"
        c.write_text("\n".join(lines))
        exe = Path(tmp) / "probe"
        subprocess.run(["gcc", "-m32", "-fpack-struct=2", "-I", str(SRC), str(c), "-o", str(exe)], check=True)
        out = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout
    return {n: int(s) for n, s in (l.split() for l in out.splitlines())}


def main() -> None:
    variables = sorted(parse(), key=lambda v: (v[1], v[0]))
    size = sizes(variables)
    # the unsized arrays go on to the next variable or table (or 4 KiB at the most is not enough for the screens: the next object)
    # (the unsized arrays of one region are used as one block: the next one does not end the first, a variable of known size or a table does)
    starts = sorted({v[1] for v in variables if size[v[0]] != 0} | {a for _, a in tables()})
    for i, (name, addr, decl) in enumerate(variables):
        if size[name] == 0:
            following = [s for s in starts if s > addr]
            size[name] = (following[0] if following else HEAP) - addr
            if name in EXTENT:
                size[name] = EXTENT[name] - addr
    # clusters of overlapping variables
    clusters = []
    for v in variables:
        name, addr, decl = v
        end = addr + size[name]
        if clusters and addr < clusters[-1]["end"]:
            clusters[-1]["members"].append(v)
            clusters[-1]["end"] = max(clusters[-1]["end"], end)
        else:
            clusters.append({"start": addr, "end": end, "members": [v]})
    out = ["/* Generated by scripts/gen_guest_struct.py from menu.symbols; do not edit.  Every variable of the program is a member of struct Guest, at the offset of its original address. */",
           "#ifndef GUEST_STRUCT_H", "#define GUEST_STRUCT_H", "", "#include <stddef.h>", "#include <stdint.h>", "", '#include "menu_types.h"', "",
           "struct Guest {"]
    at = 0
    checks = []

    unsized = {n for n, a, d in variables if re.search(r"%s\[\]", d)}

    def declare(decl, name):
        if name in unsized:   # the original does not say how long: up to the next object
            element = 4 if "*" in decl else SIZES[decl.split("%s")[0].replace("volatile", "").replace("const", "").strip()]
            decl = decl.replace("%s[]", f"%s[{max(size[name] // element, 1)}]")
        return decl.replace("%s", name) + ";"

    for c in clusters:
        if c["start"] > at:
            out.append(f"    uint8_t pad_{at:05x}[{c['start'] - at}];")
        if len(c["members"]) == 1:
            name, addr, decl = c["members"][0]
            out.append(f"    {declare(decl, name)}   /* ${addr:05X} */")
            checks.append((name, addr))
        else:
            out.append("    union {   /* the variables that overlap */")
            for name, addr, decl in c["members"]:
                if addr == c["start"]:
                    out.append(f"        struct {{ {declare(decl, name)} }};   /* ${addr:05X} */")
                else:
                    out.append(f"        struct {{ uint8_t pad_in_{addr:05x}_{len(checks)}[{addr - c['start']}]; {declare(decl, name)} }};   /* ${addr:05X} */")
                checks.append((name, addr))
            out.append(f"        uint8_t bytes_{c['start']:05x}[{c['end'] - c['start']}];")
            out.append("    };")
        at = c["end"]
    out.append(f"    uint8_t pad_{at:05x}[{HEAP - at}];")
    out.append("#ifdef GODS_HEAP_IN_GUEST   /* the host's builds: the program's heap is the end of the block */")
    out.append(f"    uint8_t heap[{GUEST_END - HEAP}];   /* ${HEAP:05X} */")
    out.append("#endif")
    out.append("};")
    out.append("")
    for name, addr in checks:
        out.append(f'_Static_assert(offsetof(struct Guest, {name}) == 0x{addr:x}, "{name}");')
    out += ["", "extern struct Guest guest;", "", "#endif", ""]
    (SRC / "guest_struct.h").write_text("\n".join(out))
    print(f"wrote guest_struct.h: {len(variables)} variables, {len(clusters)} clusters, {sum(1 for c in clusters if len(c['members']) > 1)} unions")


if __name__ == "__main__":
    main()
