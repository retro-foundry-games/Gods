"""Generate native/amiga.asm: the Amiga-specific routines (blitter work and screen fills) as the original has them.

The bodies are the original instructions, disassembled from the resident code in the reference recording (frame 1746),
with data addresses turned into symbols and branch targets into labels; so they take the same time as the original,
which the intro's timing depends on.  Around them go small wrappers with the C calling convention (arguments on the
stack, d2-d7/a2-a6 preserved).

    uv run python projects/gods/scripts/gen_amiga_asm.py
"""
import re
import subprocess
import sys
from pathlib import Path

from capstone import CS_ARCH_M68K, CS_MODE_M68K_000, Cs

ROOT = Path(__file__).resolve().parents[3]
PROJECT = ROOT / "projects" / "gods"
OUT = PROJECT / "native" / "amiga.asm"
REF = PROJECT / "captures" / "ref100k"
FRAME = 1746

# data the routines touch: original address -> (symbol, size of the object)
DATA = {
    0x2940: "_screen_front",
    0x2944: "_screen_back",
    0x298A: "_display+$42",     # blit.plane_stride
    0x298E: "_display+$46",     # blit.extra_modulo
    0x2990: "_display+$48",     # blit.mask
    0x2CB0: "_draw_flag",
    0x3486: "_blank_plane",
}
CALLS = {0x2F1E: "blitter_wait"}


def ram() -> bytes:
    tmp = PROJECT / "build" / "ref-1746.bin"
    if not tmp.exists():
        tmp.parent.mkdir(exist_ok=True)
        subprocess.run([sys.executable, str(ROOT / "tools/amiga/frame_recorder.py"), "--extract", str(REF), str(FRAME), str(tmp)],
                       check=True, capture_output=True)
    return tmp.read_bytes()


def body(mem: bytes, lo: int, hi: int, prefix: str, entries: dict[int, str] | None = None, force: set[int] = frozenset()) -> list[str]:
    """The instructions in [lo, hi) as vasm source with labels L<prefix>_<addr>."""
    md = Cs(CS_ARCH_M68K, CS_MODE_M68K_000)
    md.detail = False
    ins = list(md.disasm(mem[lo:hi], lo))
    assert sum(i.size for i in ins) == hi - lo, hex(lo)
    targets = set(force)
    for i in ins:
        if i.mnemonic.startswith(("b", "dbra")) and not i.mnemonic.startswith(("btst", "bset", "bclr", "bchg")) and "$" in i.op_str:
            targets.add(int(re.search(r"\$([0-9a-f]+)$", i.op_str).group(1), 16))
    out = []
    for i in ins:
        if i.address in (entries or {}):
            out.append(f"{entries[i.address]}:")
        if i.address in targets and i.address not in (entries or {}):
            out.append(f"{prefix}{i.address:x}:")
        op = i.op_str
        mn = i.mnemonic
        if mn.startswith(("b", "dbra")) and not mn.startswith(("btst", "bset", "bclr", "bchg")) and "$" in op:
            tgt = int(re.search(r"\$([0-9a-f]+)$", op).group(1), 16)
            if tgt in CALLS:
                op = op[: op.rindex("$")] + CALLS[tgt]
            elif tgt in (entries or {}):
                op = op[: op.rindex("$")] + entries[tgt]
            else:
                op = op[: op.rindex("$")] + f"{prefix}{tgt:x}"
            mn = mn.replace("bra.w", "bra.w").replace("bsr.w", "bsr.w")
        else:
            m = re.search(r"\$([0-9a-f]+)\.l", op)
            if m and int(m.group(1), 16) in DATA:
                op = op.replace(m.group(0), "(" + DATA[int(m.group(1), 16)] + ").l")
            elif m and int(m.group(1), 16) >= 0xDFF000:
                pass
            else:
                m = re.search(r"#\$([0-9a-f]+)", op)
                if mn.startswith("movea.l") and m and int(m.group(1), 16) in DATA:
                    op = op.replace(m.group(0), "#" + DATA[int(m.group(1), 16)])
        op = op.replace(", ", ",")
        out.append(f"        {mn} {op}".rstrip())
    return out


def scratch(lines: list[str]) -> list[str]:
    """The original keeps its counter and value in d7 and d6; in C those are callee-saved, d1 and d0 are not (same cost)."""
    return [re.sub(r"\bd6\b", "d0", re.sub(r"\bd7\b", "d1", l)) for l in lines]


def main() -> None:
    mem = ram()
    a: list[str] = []
    a += [
        "; Gods: the Amiga-specific routines, generated by scripts/gen_amiga_asm.py from the original's resident code.",
        "; The instruction sequences are the original's (the intro's timing depends on how long they take); the C calling",
        "; convention (arguments on the stack, d2-d7/a2-a6 preserved) is added around them.",
        "        xref _display, _screen_front, _screen_back, _draw_flag, _blank_plane",
        "        xdef _blitter_wait, _blit_copy, _blit_copy_right, _screen_clear, _screen_restore, _plane5_set, _plane5_clear",
        "        xdef _blit_image, _blit_image_wide, _delay, _startup_delay",
        "        section .text,code",
        "",
        "; orig $002F1E: wait until the blitter has finished (and give it priority while waiting)",
        "_blitter_wait:",
    ]
    a += body(mem, 0x2F1E, 0x2F3A, "w").copy()
    a[-1:] = ["        rts"]
    a += ["blitter_wait = _blitter_wait", ""]

    a += ["; void blit_copy(const void *src, void *dst), orig $001B7C: copy the 20 x 800 words at src to dst, A -> D",
          "_blit_copy:", "        move.l a6,-(sp)", "        movea.l 8(sp),a0", "        movea.l 12(sp),a1"]
    b = body(mem, 0x1B7C, 0x1BC6, "c")
    a += b[:-1] + ["        movea.l (sp)+,a6", "        rts", ""]

    a += ["; void blit_copy_right(const void *src, void *dst), orig $001BC6: only the right-hand 9 words of each row",
          "_blit_copy_right:", "        move.l a6,-(sp)", "        movea.l 8(sp),a0", "        movea.l 12(sp),a1"]
    b = body(mem, 0x1BC6, 0x1C18, "r")
    a += b[:-1] + ["        movea.l (sp)+,a6", "        rts", ""]

    a += ["; void screen_restore(void), orig $0030EE: copy the back screen over the front screen",
          "_screen_restore:"]
    a += body(mem, 0x30EE, 0x310E, "s")[:]
    a += ["", "; void screen_clear(void), orig $0030D4: clear the front screen", "_screen_clear:"]
    a += body(mem, 0x30D4, 0x30EE, "z")
    a += [""]
    a += ["; void plane5_set(void), orig $001D54: set the whole fifth bitplane of the front screen (d0/d1 for the original's d6/d7)"]
    a += ["_plane5_set:"] + scratch(body(mem, 0x1D54, 0x1D7E, "p"))
    a += ["", "; void plane5_clear(void), orig $001D7E: clear the fifth bitplane of the front screen", "_plane5_clear:"]
    a += scratch(body(mem, 0x1D7E, 0x1DA8, "q"))
    a += [""]

    save = "        movem.l d2-d7/a2-a4,-(sp)"
    load = ["        movea.l 40(sp),a0          ; dst", "        movea.l 44(sp),a1          ; src",
            "        move.w 50(sp),d0           ; bytes between the planes", "        move.w 54(sp),d1           ; pixel shift",
            "        move.w 58(sp),d7           ; rows"]
    a += ["; void blit_image(uint8_t *dst, const uint8_t *src, uint16_t plane, uint16_t shift, uint16_t rows), orig $0032B6:",
          "; draw an image one word wide (the planes are `plane` bytes apart) through a mask built from its planes",
          "_blit_image:", save] + load
    a += body(mem, 0x32B6, 0x32CA, "i", force={0x32DE})   # words = 1; ends with `bra.b` to the shared part
    a += ["", "; void blit_image_wide(...), orig $0032CA: the same for an image two words wide", "_blit_image_wide:", save] + load
    a += body(mem, 0x32CA, 0x32DE, "j")
    rest = body(mem, 0x32DE, 0x3486, "i", force={0x32DE})
    # the shared part ends with `rts`: restore what the wrappers saved
    idx = max(n for n, l in enumerate(rest) if l.strip() == "rts")
    rest[idx:idx + 1] = ["        movem.l (sp)+,d2-d7/a2-a4", "        rts"]
    a += rest
    a += ["", "; void delay(void), the music's busy wait (inline at orig $0024F2 and $00250A): 301 rounds of a lone dbra",
          "_delay:", "        move.w #$12c,d0", "dl:", "        dbra d0,dl", "        rts",
          "", "; void startup_delay(void), orig $000C26: a long wait before the program starts (a register loop, 18 cycles a round)",
          "_startup_delay:", "        move.l #$f4240,d0", "sd:", "        subq.l #1,d0", "        bne.b sd", "        rts"]
    OUT.write_text("\n".join(a) + "\n")
    print(f"wrote {OUT} ({len(a)} lines)")


if __name__ == "__main__":
    main()
