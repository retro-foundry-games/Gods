"""Write native/src/intro_offsets.i: the offsets of the struct fields intro_amiga.asm uses (from native/src/intro_offsets.c, compiled by the
real compiler, so they follow intro.h) and the addresses of the pinned tables it addresses with absolute short.

    uv run python projects/gods/scripts/intro_offsets.py
"""
import re
import subprocess
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
SRC = PROJECT / "native" / "src"
OUT = SRC / "intro_offsets.i"
TABLES = ("sample_start", "period_table", "vibrato_table", "channel")   # addressed absolutely by the music code


def offsets() -> dict[str, int]:
    """name -> value for every constant in intro_offsets.c."""
    r = subprocess.run(["nix", "develop", str(SRC.parent), "--command", "m68k-amigaos-gcc", "-m68000", "-ffreestanding", "-S", "-o", "-",
                        str(SRC / "intro_offsets.c")], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr)
    # a constant is `.word N`, or `.skip 2` when it is zero
    return {m.group(1): int(m.group(3) or 0) for m in re.finditer(r"^_(\w+):\n\s+(\.(?:word|short|long|byte)\s+(\d+)|\.skip\s+\d+)", r.stdout, re.M)}


def write() -> dict[str, int]:
    values = offsets()
    addresses = {name: int(addr, 16) for name, addr in (l.split() for l in (SRC / "intro.objects").read_text().split("\n") if l.strip())}
    lines = ["; Generated by scripts/intro_offsets.py from native/src/intro_offsets.c and native/src/intro.objects; do not edit.",
             "; offsets of the fields of the structs in intro.h"]
    lines += [f"{name} = ${value:x}" for name, value in values.items()]
    lines += ["; where the pinned tables are (the addresses intro.ld gives them), for absolute short addressing"]
    lines += [f"Addr_{name} = ${addresses[name]:x}" for name in TABLES]
    OUT.write_text("\n".join(lines) + "\n")
    return values


if __name__ == "__main__":
    print(f"wrote {OUT} ({len(write())} constants)")
