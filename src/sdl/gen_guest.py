#!/usr/bin/env python3
"""Write the host build's linker symbols, function stubs and table list from native/src/menu.symbols.

    gen_guest.py SRC_DIR OUT_DIR

The game keeps its variables in struct Guest (guest_struct.h, guest.c).
  g_stubs.c           the symbols that are routines of the original's code (`void fn_30c6(void)` ...) are not in the host program:
                      they are functions that log the call and return
  guest_tables.h      the `table` lines (constant data of data.c): guest.c copies them to their addresses; they are native-endian
                      C data, the bytes of the disk image are not, so the loader keeps them
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

LOW_BASE = 0x01000000
GUEST_END = 0x00200000
LOW_LIMIT = 0x10000

src, out = Path(sys.argv[1]), Path(sys.argv[2])
tables: list[tuple[str, int, int]] = []   # name, address, size in bytes
variables: list[tuple[str, int]] = []
stubs: list[tuple[str, str]] = []         # name, return type
declarations: dict[str, str] = {}         # the variables' declarations (%s for the name)
SIZES = {"char": 1, "uint8_t": 1, "uint16_t": 2, "uint32_t": 4}

for line in (src / "menu.symbols").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    parts = line.split()
    if parts[0] == "table":
        if parts[3] == "struct":   # table NAME ADDR struct NAME COUNT: the structs of menu_types.h
            tables.append((parts[1], int(parts[2], 16), {"CreatureEntry": 16, "CreatureTemplate": 16, "PathDescription": 28, "LevelEnd": 34, "LevelEnds": 580, "SoundRecord": 6, "SoundInstrument": 14, "WalkMode": 8}[parts[4]] * int(parts[5])))
            continue
        name, addr, ty, count = parts[1], int(parts[2], 16), parts[3], int(parts[4])
        tables.append((name, addr, SIZES[ty] * count))
        continue
    name, addr = parts[0], int(parts[1], 16)
    decl = line.split(None, 2)[2]
    m = re.match(r"(.*?)\s*%s\(void\)", decl)
    if m and "(*" not in decl:
        stubs.append((name, m.group(1).strip()))
    else:
        variables.append((name, addr))
        dm = re.match(r"(.*?%s.*?)(?:\s{2,}.*)?$", decl)
        declarations[name] = dm.group(1).strip() if dm else decl.strip()


def host(addr: int) -> int:
    return addr + LOW_BASE if addr < LOW_LIMIT else addr


c = ["/* generated by sdl/gen_guest.py: the routines of the original's code the program calls but the host does not have */",
     "#include <stdint.h>", "#include <stdio.h>", ""]
HOST_PROVIDED = {"original_begin", "original_continue", "original_after_password"}   # shims.c: the host's Begin Quest
for name, ret in stubs:
    if name in HOST_PROVIDED:
        continue
    value = "" if ret == "void" else " 0"
    c.append(f'{ret} {name}(void) {{ static int said; if (!said++) fprintf(stderr, "gods-sdl: original routine {name} called (not in C): skipped\\n"); return{value}; }}')
(out / "g_stubs.c").write_text("\n".join(c) + "\n")

h = ["/* generated by sdl/gen_guest.py */", f"#define GUEST_LOW_BASE {hex(LOW_BASE)}u", f"#define GUEST_LOW_LIMIT {hex(LOW_LIMIT)}u",
     f"#define GUEST_END {hex(GUEST_END)}u"]
h.append("static const struct { uint32_t address, size; const uint8_t *data; } guest_tables[] = {")
for name, addr, size in sorted(tables, key=lambda t: t[1]):
    h.append(f"    {{ {hex(addr)}, {size}, (const uint8_t *){name} }},")
h.append("};")
(out / "guest_tables.h").write_text("\n".join(h) + "\n")

