#!/usr/bin/env python3
"""Write guest_fixups.h from native/src/game.symbols: for a RAM image of the original (a test of the level on the host) which words and
longs of each variable are to be swapped to the host's byte order.

    gen_fixups.py SRC_DIR OUT_DIR

The types are the declarations of game.symbols; the structs are the ones of game.h as (offset, width) of every field wider than a byte.
Variables of unknown length (`name[]`) are left alone.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])

STRUCTS = {
    "MemLists": (20, [(0, 4), (4, 4), (8, 4), (12, 4), (16, 4)]),
    "AssetEntry": (8, [(0, 2), (2, 2), (4, 5)]),   # (the planes' address)
    "Slot8": (8, [(0, 2), (2, 2), (4, 2), (6, 2)]),
    "Slot12": (12, [(2 * i, 2) for i in range(6)]),
    "Rec6": (6, [(0, 2), (2, 2), (4, 2)]),
    "Rec10": (10, [(2 * i, 2) for i in range(5)]),
    # struct Rec80 is used as struct Object (80 bytes)
    "Rec80": (80, [(0, 2), (2, 2), (4, 2), (6, 2), (8, 2), (10, 2), (12, 2), (14, 2), (20, 4), (24, 4), (28, 2), (30, 2), (74, 2)]),
    "Entry8": (8, [(0, 4), (4, 4)]),
    "Image": (8, [(0, 2), (2, 2), (4, 4)]),
    "Shot": (8, [(0, 2), (2, 2), (4, 2), (6, 2)]),
    "Voice": (148, []),
    "LevelData": (7160, [(6000 + 2 * i, 2) for i in range(90)] + [(6180 + 2 * i, 2) for i in range(60)]),   # (the teleport gems and the pick-ups: words)
    "ShotList": (146, [(2 * i, 2) for i in range(73)]),   # (the number of the object and 18 shots of four words)
    "SoundState": (14, [(2, 4)]),   # (busy: the long the loader writes)
    "CopperLists": (1408, [(6, 2), (90, 2), (176, 2), (0x4BC, 2), (0x4CA, 2), (0x4CC, 2), (0x4CE, 2)]),   # (the COLOR01 words of the two lists, the first of the bands, and the words of the message that the program writes: its WAIT and its bitplane pointer; the rest of the lists is made native by guest_load.c)
    "Monster": (428, [(0, 2), (2, 5), (6, 2), (20, 2), (22, 2)] + [(24 + 2 * i, 2) for i in range(200)] + [(424, 2)]),
    "Bolt": (22, [(0, 4)] + [(4 + 2 * i, 2) for i in range(9)]),
    "Unit": (24, [(0, 2), (4, 2), (10, 4), (14, 2), (16, 2), (18, 4)]),
    "WalkGroup": (18, [(0, 2), (2, 5)]),
    "Planner": (34, [(2 * i, 2) for i in range(17)]),
    "PlanItem": (8, [(0, 2), (2, 2), (4, 2), (6, 2)]),
}
POINTER_LONGS = {"marker_table", "screen_list_cursor"}   # variables typed as longs that hold addresses (cells, the list of the records that go along)
fixups: set[tuple[int, int, int]] = set()   # address, width, count
for line in (src / "game.symbols").read_text().splitlines():
    if not line.strip() or line.startswith("#") or line.split()[0] == "table" or "(void)" in line:
        continue
    parts = line.split()
    addr = int(parts[1], 16)
    decl = line.split(None, 2)[2]
    m = re.match(r"(.*?)\s*%s(?:\[(\d*)\])?", decl)
    if not m or "(*" in decl:
        continue
    ty, count = m.group(1).replace("volatile", "").replace("const", "").strip(), m.group(2)
    n = 1 if count is None else int(count) if count else 0
    if "*" in ty:
        fixups.add((addr, 5, n or 1))   # width 5: a pointer (4 bytes; a value below 64 KiB is in the memory that is moved up)
        continue
    base = ty.replace("struct", "").strip()
    if base in STRUCTS:
        size, fields = STRUCTS[base]
        if parts[0] == "entry_table":   # declared as records of three words, used as struct SavedByte: an address and a word
            fields = [(0, 5), (4, 2)]   # an address (the byte a record undoes) and a word
        for i in range(n or 1):
            for off, width in fields:
                fixups.add((addr + i * size + off, width, 1))
        continue
    width = {"uint16_t": 2, "int16_t": 2, "uint32_t": 4, "int32_t": 4}.get(base)
    if parts[0] in POINTER_LONGS and base == "uint32_t":
        width = 5   # longs that hold addresses of the program's memory
    if width:
        fixups.add((addr, width, n or (16 if parts[0] == "shadow_table" else 1)))
f = ["/* generated by sdl/gen_fixups.py */", "static const struct { uint32_t address; uint8_t width; uint16_t count; } guest_fixups[] = {"]
for a, w, c in sorted(fixups):
    f.append(f"    {{ {hex(a)}, {w}, {c} }},")
f.append("};")
(out / "guest_fixups.h").write_text("\n".join(f) + "\n")
